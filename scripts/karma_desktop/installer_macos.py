def add_to_dock(app: Path) -> bool:
    """Pin ``app`` to the Dock, replacing any previous Karma tile.

    Two non-obvious details, both learned the hard way:

    * The Dock writes its in-memory state back on SIGTERM, so a plain
      ``killall Dock`` silently reverts whatever was just written. It has to be
      SIGKILL.
    * Each tile carries a ``book`` bookmark blob encoding the resolved target.
      Changing only the URL leaves the Dock resolving the stale bookmark, so
      the bookmark and its mod-dates must be dropped and regenerated.
    """
    try:
        raw = subprocess.run(
            ["defaults", "export", "com.apple.dock", "-"],
            capture_output=True,
            check=True,
        ).stdout
        plist = plistlib.loads(raw)
    except (subprocess.SubprocessError, OSError, plistlib.InvalidFileException):
        return False

    apps = plist.get("persistent-apps", [])
    url = app.as_uri()
    if not url.endswith("/"):
        url += "/"

    # Any existing Karma tile is replaced -- including the browser-installed
    # PWA shim, which looks identical but cannot start the servers. Leaving
    # both pinned is the single most confusing outcome for a user.
    existing = [i for i, a in enumerate(apps) if _is_replaceable_karma_tile(a)]
    # Reuse the first one's slot so the icon stays where muscle memory expects
    # it; appending would drop it at the far right of the Dock.
    insert_at = existing[0] if existing else len(apps)
    apps = [a for a in apps if not _is_replaceable_karma_tile(a)]

    apps.insert(
        insert_at,
        {
            "tile-type": "file-tile",
            "tile-data": {
                "file-type": 41,
                "file-label": core.APP_NAME,
                "bundle-identifier": BUNDLE_ID,
                "file-data": {"_CFURLString": url, "_CFURLStringType": 15},
            },
        },
    )
    plist["persistent-apps"] = apps
    return _write_dock(plist)


# Exact labels the browser gives a Karma PWA shim. Matched exactly, never as a
# substring, so "karma-tools" or a repo path containing "karma" is never hit.
_PWA_LABELS = {"Karma", "Claude Code Karma"}
_BROWSER_APP_PREFIXES = ("com.google.Chrome.app.", "com.microsoft.edgemac.app.")


def _is_replaceable_karma_tile(tile: dict) -> bool:
    """True for a tile install may replace: our own launcher, or a Karma PWA.

    Matched by bundle identifier and *exact* label only. The previous version
    matched the substring "karma" anywhere in the tile's file URL, which is a
    full ``file:///...`` path -- so any app under a directory containing
    "karma" (including a checkout of this repo) would be silently unpinned.
    """
    td = tile.get("tile-data", {})
    bundle = td.get("bundle-identifier") or ""
    label = td.get("file-label") or ""
    if bundle == BUNDLE_ID:  # our launcher
        return True
    # A browser-installed Karma PWA: exact Karma label AND a browser app id.
    return label in _PWA_LABELS and bundle.startswith(_BROWSER_APP_PREFIXES)


def _write_dock(plist: dict) -> bool:
    """Persist a modified Dock plist and restart the Dock.

    SIGKILL, not SIGTERM: the Dock rewrites its in-memory state back on a
    graceful termination, silently reverting whatever was just imported.
    """
    tmp = Path(
        subprocess.run(["mktemp"], capture_output=True, text=True).stdout.strip()
    )
    try:
        with open(tmp, "wb") as fh:
            plistlib.dump(plist, fh)
        subprocess.run(["defaults", "import", "com.apple.dock", str(tmp)], check=True)
        time.sleep(1)
        subprocess.run(["killall", "-9", "Dock"], capture_output=True)
        time.sleep(2)
        return True
    except (subprocess.SubprocessError, OSError):
        return False
    finally:
        tmp.unlink(missing_ok=True)


def unpin_from_dock() -> bool:
    """Remove the launcher's Dock tile. True if a tile was actually removed.

    Used when autostart is enabled: the servers then come up at login, so the
    launcher never needs clicking, and a pinned launcher tile only competes
    with the browser-installed PWA icon the user actually wants. This matches
    only the launcher's own bundle id, so it never touches a PWA tile the user
    pinned themselves.
    """
    try:
        raw = subprocess.run(
            ["defaults", "export", "com.apple.dock", "-"],
            capture_output=True,
            check=True,
        ).stdout
        plist = plistlib.loads(raw)
    except (subprocess.SubprocessError, OSError, plistlib.InvalidFileException):
        return False

    apps = plist.get("persistent-apps", [])
    kept = [
        a
        for a in apps
        if (a.get("tile-data", {}).get("bundle-identifier") or "") != BUNDLE_ID
    ]
    if len(kept) == len(apps):
        return False
    plist["persistent-apps"] = kept
    return _write_dock(plist)



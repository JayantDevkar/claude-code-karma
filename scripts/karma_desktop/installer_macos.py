"""macOS side of the desktop installer: a ``.app`` bundle, optionally pinned
to the Dock, optionally started at login by launchd."""

from __future__ import annotations

import os
import plistlib
import shutil
import subprocess
import time
from pathlib import Path

from . import core

BUNDLE_ID = "com.claudecodekarma.launcher"
AGENT_LABEL = "com.claudecodekarma.servers"

# The bundle executable is a thin shell stub; all real logic stays in the repo
# so that pulling new commits updates the launcher with no reinstall.
#
# The arch guard matters: LaunchServices runs script-only .app bundles under
# Rosetta on Apple Silicon, which makes a universal node pick its Intel slice
# and then demand @rollup/rollup-darwin-x64, which is never installed.
_STUB = """#!/bin/bash
# Generated by scripts/install_karma_app.py -- edits here are overwritten.
if [ "$(sysctl -n sysctl.proc_translated 2>/dev/null)" = "1" ]; then
  exec arch -arm64 "$0" "$@"
fi
LAUNCHER={launcher}
# The repo may have moved, been renamed, or (if it was a git worktree) pruned.
# Without this check the app would exec a missing file and die instantly with
# no window and no message -- a permanently dead icon.
if [ ! -f "$LAUNCHER" ]; then
  /usr/bin/osascript -e 'display alert "Karma" message "Karma cannot find its files -- the project folder was moved or removed. Reinstall the desktop app from the dashboard (Settings -> Desktop App), or drag this app to the Trash." as critical' >/dev/null 2>&1
  exit 1
fi
exec {python} "$LAUNCHER" --web-port {web_port} --api-port {api_port} "$@"
"""


def _shq(path: Path | str) -> str:
    import shlex

    return shlex.quote(str(path))


def _is_our_bundle(app: Path) -> bool:
    """True only if ``app``'s Info.plist carries our bundle identifier."""
    info = app / "Contents" / "Info.plist"
    try:
        with open(info, "rb") as fh:
            return plistlib.load(fh).get("CFBundleIdentifier") == BUNDLE_ID
    except (OSError, plistlib.InvalidFileException):
        return False


def _build_bundle(
    dest: Path, repo: Path, python: Path, web_port: int, api_port: int
) -> None:
    """Write a complete .app bundle at ``dest``. All the fallible I/O lives here
    so it can be done off to the side and swapped in atomically."""
    macos = dest / "Contents" / "MacOS"
    resources = dest / "Contents" / "Resources"
    macos.mkdir(parents=True)
    resources.mkdir(parents=True)

    launcher = repo / "scripts" / "karma_desktop" / "launcher.py"
    stub = macos / core.APP_NAME
    stub.write_text(
        _STUB.format(
            python=_shq(python),
            launcher=_shq(launcher),
            web_port=web_port,
            api_port=api_port,
        ),
        encoding="utf-8",
    )
    stub.chmod(0o755)

    icon_src = repo / "frontend" / "static" / "icons" / "karma.icns"
    icon_name = ""
    if icon_src.is_file():
        shutil.copy2(icon_src, resources / "Karma.icns")
        icon_name = "Karma"

    info = {
        "CFBundleName": core.APP_NAME,
        "CFBundleDisplayName": core.APP_NAME,
        "CFBundleIdentifier": BUNDLE_ID,
        "CFBundleExecutable": core.APP_NAME,
        "CFBundlePackageType": "APPL",
        "CFBundleVersion": "1.0",
        "CFBundleShortVersionString": "1.0",
        # Agent app: a "starting" notification is the user-visible feedback, so
        # the bundle itself never needs a Dock tile of its own.
        "LSUIElement": True,
    }
    if icon_name:
        info["CFBundleIconFile"] = icon_name
    with open(dest / "Contents" / "Info.plist", "wb") as fh:
        plistlib.dump(info, fh)


def install_app(
    repo: Path,
    python: Path,
    app_dir: Path,
    web_port: int,
    api_port: int,
) -> Path:
    """Create ``<app_dir>/Karma.app`` atomically and return its path.

    Refuses to overwrite an existing ``Karma.app`` that is not ours -- "Karma"
    is not a rare product name, and blindly ``rmtree``-ing whatever sits there
    would delete an unrelated vendor's app.

    The bundle is built in a temp directory beside the target and swapped in
    with directory renames, so a failure partway through (permission denied on
    the write, disk full, a symlink in the way) never leaves a destroyed or
    half-written bundle at the target that ``status`` would then report as
    "installed".
    """
    app = app_dir / f"{core.APP_NAME}.app"
    if app.exists() and not _is_our_bundle(app):
        raise FileExistsError(
            f"{app} already exists and is not the Karma launcher "
            f"(bundle id != {BUNDLE_ID}). Refusing to overwrite it."
        )

    tmp = app_dir / f".{core.APP_NAME}.app.tmp.{os.getpid()}"
    backup = app_dir / f".{core.APP_NAME}.app.bak.{os.getpid()}"
    shutil.rmtree(tmp, ignore_errors=True)
    try:
        _build_bundle(tmp, repo, python, web_port, api_port)
        # Move the old bundle aside, swing the new one in, then drop the old.
        # If the swap fails, the original is restored, so the target is never
        # left broken.
        if app.exists():
            os.replace(app, backup)
        try:
            os.replace(tmp, app)
        except OSError:
            if backup.exists():
                os.replace(backup, app)
            raise
    finally:
        shutil.rmtree(tmp, ignore_errors=True)
        shutil.rmtree(backup, ignore_errors=True)

    _refresh_launch_services(app)
    return app


_LSREGISTER = (
    "/System/Library/Frameworks/CoreServices.framework/Versions/A/Frameworks/"
    "LaunchServices.framework/Versions/A/Support/lsregister"
)


def _refresh_launch_services(app: Path) -> None:
    """Get LaunchServices to notice the new bundle so its icon repaints.

    ``lsregister -f`` is the actual LaunchServices refresh; a bare ``touch`` on
    the bundle mtime does not reliably repaint the icon. Both are best-effort --
    the icon settles on its own eventually -- so failures are ignored. Absolute
    paths, matching the rest of this module, so a stripped PATH can't break it.
    """
    if Path(_LSREGISTER).exists():
        subprocess.run([_LSREGISTER, "-f", str(app)], capture_output=True)
    else:
        subprocess.run(["/usr/bin/touch", str(app)], capture_output=True)



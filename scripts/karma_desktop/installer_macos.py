"""macOS side of the desktop installer: a ``.app`` bundle, optionally pinned
to the Dock, optionally started at login by launchd."""

from __future__ import annotations

import plistlib
import shutil
import subprocess
import time
from pathlib import Path

from . import core

BUNDLE_ID = "com.claudecodekarma.launcher"
AGENT_LABEL = "com.claudecodekarma.servers"

# The bundle executable is a thin shell stub; all real logic stays in the repo
# so that pulling new commits updates the launcher with no reinstall.
#
# The arch guard matters: LaunchServices runs script-only .app bundles under
# Rosetta on Apple Silicon, which makes a universal node pick its Intel slice
# and then demand @rollup/rollup-darwin-x64, which is never installed.
_STUB = """#!/bin/bash
# Generated by scripts/install_karma_app.py -- edits here are overwritten.
if [ "$(sysctl -n sysctl.proc_translated 2>/dev/null)" = "1" ]; then
  exec arch -arm64 "$0" "$@"
fi
exec {python} {launcher} --web-port {web_port} --api-port {api_port} "$@"
"""


def _shq(path: Path | str) -> str:
    import shlex

    return shlex.quote(str(path))


def install_app(
    repo: Path,
    python: Path,
    app_dir: Path,
    web_port: int,
    api_port: int,
) -> Path:
    """Create ``<app_dir>/Karma.app`` and return its path."""
    app = app_dir / f"{core.APP_NAME}.app"
    if app.exists():
        shutil.rmtree(app)

    macos = app / "Contents" / "MacOS"
    resources = app / "Contents" / "Resources"
    macos.mkdir(parents=True)
    resources.mkdir(parents=True)

    launcher = repo / "scripts" / "karma_desktop" / "launcher.py"
    stub = macos / core.APP_NAME
    stub.write_text(
        _STUB.format(
            python=_shq(python),
            launcher=_shq(launcher),
            web_port=web_port,
            api_port=api_port,
        ),
        encoding="utf-8",
    )
    stub.chmod(0o755)

    icon_src = repo / "frontend" / "static" / "icons" / "karma.icns"
    icon_name = ""
    if icon_src.is_file():
        shutil.copy2(icon_src, resources / "Karma.icns")
        icon_name = "Karma"

    info = {
        "CFBundleName": core.APP_NAME,
        "CFBundleDisplayName": core.APP_NAME,
        "CFBundleIdentifier": BUNDLE_ID,
        "CFBundleExecutable": core.APP_NAME,
        "CFBundlePackageType": "APPL",
        "CFBundleVersion": "1.0",
        "CFBundleShortVersionString": "1.0",
        # Agent app: the splash window is the user-visible feedback, so the
        # bundle itself never needs a Dock tile of its own.
        "LSUIElement": True,
    }
    if icon_name:
        info["CFBundleIconFile"] = icon_name
    with open(app / "Contents" / "Info.plist", "wb") as fh:
        plistlib.dump(info, fh)

    # Nudge LaunchServices so the icon appears without a logout.
    subprocess.run(["touch", str(app)], capture_output=True)
    return app


# --------------------------------------------------------------------------
# Dock
# --------------------------------------------------------------------------


def add_to_dock(app: Path) -> bool:
    """Pin ``app`` to the Dock, replacing any previous Karma tile.

    Two non-obvious details, both learned the hard way:

    * The Dock writes its in-memory state back on SIGTERM, so a plain
      ``killall Dock`` silently reverts whatever was just written. It has to be
      SIGKILL.
    * Each tile carries a ``book`` bookmark blob encoding the resolved target.
      Changing only the URL leaves the Dock resolving the stale bookmark, so
      the bookmark and its mod-dates must be dropped and regenerated.
    """
    try:
        raw = subprocess.run(
            ["defaults", "export", "com.apple.dock", "-"],
            capture_output=True,
            check=True,
        ).stdout
        plist = plistlib.loads(raw)
    except (subprocess.SubprocessError, OSError, plistlib.InvalidFileException):
        return False

    apps = plist.get("persistent-apps", [])
    url = app.as_uri()
    if not url.endswith("/"):
        url += "/"

    def _is_karma_tile(tile: dict) -> bool:
        td = tile.get("tile-data", {})
        haystack = (td.get("file-label") or "") + (
            td.get("file-data", {}).get("_CFURLString") or ""
        )
        return core.APP_NAME.lower() in haystack.lower()

    # Any existing Karma tile is replaced -- including the browser-installed
    # PWA shim, which looks identical but cannot start the servers. Leaving
    # both pinned is the single most confusing outcome for a user.
    existing = [i for i, a in enumerate(apps) if _is_karma_tile(a)]
    # Reuse the first one's slot so the icon stays where muscle memory expects
    # it; appending would drop it at the far right of the Dock.
    insert_at = existing[0] if existing else len(apps)
    apps = [a for a in apps if not _is_karma_tile(a)]

    apps.insert(
        insert_at,
        {
            "tile-type": "file-tile",
            "tile-data": {
                "file-type": 41,
                "file-label": core.APP_NAME,
                "bundle-identifier": BUNDLE_ID,
                "file-data": {"_CFURLString": url, "_CFURLStringType": 15},
            },
        },
    )
    plist["persistent-apps"] = apps

    tmp = Path(
        subprocess.run(["mktemp"], capture_output=True, text=True).stdout.strip()
    )
    try:
        with open(tmp, "wb") as fh:
            plistlib.dump(plist, fh)
        subprocess.run(["defaults", "import", "com.apple.dock", str(tmp)], check=True)
        time.sleep(1)
        subprocess.run(["killall", "-9", "Dock"], capture_output=True)
        time.sleep(2)
        return True
    except (subprocess.SubprocessError, OSError):
        return False
    finally:
        tmp.unlink(missing_ok=True)



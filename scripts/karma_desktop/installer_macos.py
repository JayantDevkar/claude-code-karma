def agent_path() -> Path:
    return Path.home() / "Library" / "LaunchAgents" / f"{AGENT_LABEL}.plist"


def autostart_enabled() -> bool:
    """Whether the launchd login item is *installed*.

    This reports the presence of the agent plist, not whether macOS will run
    it at login. On Ventura and later the user can disable the item under
    System Settings -> General -> Login Items; that records a disabled state in
    the system's background-items database while the plist file stays on disk,
    and there is no reliable, non-root way to read that state. So a True result
    means "we installed it", not "it is guaranteed to run at login" -- do not
    claim the two are the same.
    """
    return agent_path().exists()


def _autostart_command(
    plist_path: Path, python: Path, launcher: Path, web_port: int, api_port: int
) -> list[str]:
    """launchd ProgramArguments that self-heal when the repo is gone.

    If the launcher no longer exists (repo moved / deleted / worktree pruned),
    the agent unloads and deletes *itself* instead of failing at every login
    forever -- otherwise the user is left with a phantom login item that only a
    manual ``rm ~/Library/LaunchAgents/...`` can clear, because the dashboard
    that could remove it died with the repo.
    """
    script = (
        f"if [ ! -f {_shq(launcher)} ]; then "
        f"/bin/launchctl unload {_shq(plist_path)} 2>/dev/null; "
        f"/bin/rm -f {_shq(plist_path)}; exit 0; fi; "
        f"exec {_shq(python)} {_shq(launcher)} --no-open --quiet "
        f"--web-port {web_port} --api-port {api_port}"
    )
    return ["/bin/bash", "-c", script]


def install_autostart(repo: Path, python: Path, web_port: int, api_port: int) -> Path:
    """Install a launchd agent that starts the servers at login."""
    plist_path = agent_path()
    plist_path.parent.mkdir(parents=True, exist_ok=True)
    launcher = repo / "scripts" / "karma_desktop" / "launcher.py"
    logs = core.log_dir()

    payload = {
        "Label": AGENT_LABEL,
        "ProgramArguments": _autostart_command(
            plist_path, python, launcher, web_port, api_port
        ),
        "RunAtLoad": True,
        # The launcher exits once the servers are up; it is not the thing to
        # keep alive, so KeepAlive stays off to avoid a restart loop.
        "KeepAlive": False,
        # A login-time `npm run dev` compile is heavy; run it as a background
        # task with low-priority I/O and a lower niceness so it yields to the
        # rest of login (Finder, menu bar, the user's own apps) rather than
        # competing at default priority.
        "ProcessType": "Background",
        "LowPriorityIO": True,
        "Nice": 5,
        "StandardOutPath": str(logs / "autostart.log"),
        "StandardErrorPath": str(logs / "autostart.log"),
    }
    with open(plist_path, "wb") as fh:
        plistlib.dump(payload, fh)

    # launchctl load/unload is the legacy interface (bootstrap/bootout gui/$UID
    # is the modern one), but it still works on macOS 13-15. It only activates
    # the agent for *this* session; loginwindow loads the plist from disk at the
    # next login regardless, so a load failure now does not mean it won't run at
    # login -- but it can flag a malformed plist, so don't swallow it.
    subprocess.run(["launchctl", "unload", str(plist_path)], capture_output=True)
    load = subprocess.run(["launchctl", "load", str(plist_path)], capture_output=True)
    if load.returncode != 0:
        try:
            with open(logs / "autostart.log", "a", encoding="utf-8") as fh:
                fh.write(
                    "launchctl load returned "
                    f"{load.returncode}: {load.stderr.decode(errors='replace').strip()}\n"
                )
        except OSError:
            pass
    return plist_path


def uninstall_autostart() -> bool:
    """Stop Karma starting at login. True if an agent was actually removed.

    Unloading before deleting matters: a plist removed while still loaded
    leaves launchd holding the job until the next logout.
    """
    plist_path = agent_path()
    if not plist_path.exists():
        return False
    subprocess.run(["launchctl", "unload", str(plist_path)], capture_output=True)
    plist_path.unlink(missing_ok=True)
    return True


def uninstall(app_dirs: list[Path]) -> list[str]:
    """Remove the bundle, Dock tile and launchd agent. Returns what was removed.

    Each step is independent: a permission error deleting the bundle must not
    prevent the login item and Dock tile from also being cleaned up (otherwise
    "Remove" could 500 while leaving the login item installed).
    """
    removed = []
    for d in app_dirs:
        app = d / f"{core.APP_NAME}.app"
        # Only ever delete our own launcher, never a same-named vendor app.
        if app.exists() and _is_our_bundle(app):
            try:
                shutil.rmtree(app)
                removed.append(str(app))
            except OSError:
                pass

    plist_path = agent_path()
    if uninstall_autostart():
        removed.append(str(plist_path))

    # Removing the launcher's Dock tile goes through the same _write_dock path
    # as pin/unpin -- one implementation, so the killall-9 timing that makes the
    # write actually land can't drift out of sync between two copies.
    if unpin_from_dock():
        removed.append("Dock tile")

    return removed
